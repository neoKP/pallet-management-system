import { Transaction, PalletId, Partner } from '../types';
import { EXTERNAL_PARTNERS, BRANCHES, PALLET_TYPES } from '../constants';
import { getPartnerBalanceContribution } from './businessLogic';
import { getAgingRentalAnalysis } from '../services/analyticsService';

/**
 * ข้อมูลสำหรับหน้า "คู่ค้าดูอย่างเดียว" (เช่น พนักงาน บ. ซีโน-แปซิฟิค)
 *
 * หลักการ:
 * - ใช้สูตรยอดค้างเดิมของระบบ (getPartnerBalanceContribution) ทุกแถว
 *   ยอดในหน้าคู่ค้าจึงตรงกับยอดที่ทีมเราเห็นในแดชบอร์ดเสมอ
 * - ส่งออกเฉพาะช่องที่คู่ค้าควรเห็น — ไม่มีชื่อคนขับ ทะเบียนรถ หมายเหตุภายใน
 *   หรือยอดเงินค่าเช่า (เรื่องเงินให้ผู้บริหารตัดสินใจก่อนเปิดให้คู่ค้าเห็น)
 */

export interface PartnerBalanceRow {
    palletId: PalletId;
    palletName: string;
    /** จำนวนที่คู่ค้าส่งให้เรา (รวมทั้งหมด) */
    received: number;
    /** จำนวนที่เราคืนคู่ค้า (รวมทั้งหมด) */
    returned: number;
    /**
     * ยอดสุทธิตามสูตรระบบ: ลบ = เรายืมอยู่ (ค้างคืน), บวก = คืนเกิน
     * รวมยอดตั้งต้น / ปรับยอดแล้ว
     */
    balance: number;
}

/** RECEIVE = คู่ค้าส่งให้เรา · RETURN = เราคืน · AUTO = คืนอัตโนมัติโดยระบบ · ADJUST = ยอดตั้งต้น / ปรับยอด */
export type PartnerHistoryKind = 'RECEIVE' | 'RETURN' | 'AUTO' | 'ADJUST';

export interface PartnerHistoryRow {
    id: number;
    date: string;
    docNo: string;
    kind: PartnerHistoryKind;
    palletId: PalletId;
    palletName: string;
    qty: number;
    /** ผลต่อยอดค้าง (สูตรเดียวกับ balance) */
    effect: number;
    /** สาขาฝั่งเราที่รับ/คืน */
    branchName: string;
}

export interface PartnerAgingRow {
    docNo: string;
    palletId: PalletId;
    palletName: string;
    borrowDate: string;
    ageDays: number;
    qty: number;
    overdueDays: number;
}

export interface PartnerPortalView {
    partner: Partner;
    /**
     * แสดงยอดรวม / อายุค้างหรือไม่ (จาก Partner.portalShowTotals)
     * ถ้า false — balances และ aging เป็นอาร์เรย์ว่าง ไม่ส่งตัวเลขไปหน้าจอเลย
     */
    showTotals: boolean;
    balances: PartnerBalanceRow[];
    history: PartnerHistoryRow[];
    aging: PartnerAgingRow[];
    /** จำนวนวันฟรีของคู่ค้า (จากทะเบียนคู่ค้า) */
    graceDays: number;
}

/**
 * รูปแบบที่ส่งให้หน้าเว็บของคู่ค้าจริง — ข้อมูลคู่ค้าเหลือแค่รหัสกับชื่อ
 * (ตัดอัตราค่าเช่า กติกาสาขา และสวิตช์ภายในออก)
 */
export type PartnerPortalPublicView = Omit<PartnerPortalView, 'partner'> & { partner: Pick<Partner, 'id' | 'name'> };

export const toPublicView = (view: PartnerPortalView): PartnerPortalPublicView => ({
    ...view,
    partner: { id: view.partner.id, name: view.partner.name },
});

const palletName = (id: PalletId) => PALLET_TYPES.find(p => p.id === id)?.name || id;
const branchName = (id: string) => BRANCHES.find(b => b.id === id)?.name || id;

/**
 * รายการ "คืนซีโน่อัตโนมัติ" ที่ระบบสร้างเองเมื่อศูนย์ NW รับจากซีโน่
 * (hooks/useMovementLogic.ts — docNo ลงท้าย -AUTO, note "Auto-generated from ...")
 * คุณเท็นยืนยัน 28 ต.ค. 69 ว่า auto-flow นี้ไม่ใช่การคืนจริง จึงไม่แสดงเป็น "นีโอสยามคืน"
 */
export const isAutoGeneratedRow = (t: Transaction): boolean =>
    (typeof t.docNo === 'string' && t.docNo.endsWith('-AUTO')) ||
    (typeof t.note === 'string' && t.note.startsWith('Auto-generated from'));

/**
 * หน้าคู่ค้ารองรับเฉพาะคู่ค้าแบบ "เรายืมจากเขา" ปกติ (provider ไม่มี mappingName)
 * คู่ค้าที่มีสูตรพิเศษ (Loscam วังน้อย นับจากแถว neo_corp) หรือฝั่งลูกค้า
 * ป้ายกำกับ "ส่งให้นีโอสยาม / นีโอสยามคืน" จะผิดความหมาย จึงไม่เปิดให้
 */
export const isPortalSupportedPartner = (partner: Partner): boolean =>
    partner.type === 'provider' && !partner.mappingName && partner.id !== 'loscam_wangnoi';

/**
 * สร้างข้อมูลหน้าคู่ค้า
 * คืนค่า null ถ้าไม่พบคู่ค้า หรือคู่ค้ายังไม่รองรับหน้านี้ — ผู้เรียกต้องแสดงข้อความแทนการเดาข้อมูล
 */
export const buildPartnerPortalView = (
    transactions: Transaction[],
    partnerId: string,
    today: Date = new Date(),
    partners: Partner[] = EXTERNAL_PARTNERS
): PartnerPortalView | null => {
    const partner = partners.find(p => p.id === partnerId);
    if (!partner || !isPortalSupportedPartner(partner)) return null;
    const showTotals = partner.portalShowTotals === true;

    const pallets = (partner.allowedPallets ?? []) as PalletId[];

    // แถวที่มีผลต่อยอดของคู่ค้ารายนี้ (สูตรเดียวกับยอดค้าง)
    // จึงไม่มีทางดึงรายการของคู่ค้ารายอื่น / รายการรอดำเนินการ / ยกเลิก มาแสดง
    const all: PartnerHistoryRow[] = [];
    for (const t of transactions) {
        if (!t || !pallets.includes(t.palletId)) continue;
        const effect = getPartnerBalanceContribution(t, partnerId, t.palletId);
        if (effect === 0) continue;

        const isAdjust = t.type === 'ADJUST' || !!t.isInitial;
        const kind: PartnerHistoryKind = isAdjust
            ? 'ADJUST'
            : t.source === partnerId
                ? 'RECEIVE'
                : isAutoGeneratedRow(t) ? 'AUTO' : 'RETURN';
        const ourSide = t.source === partnerId ? t.dest : t.source;

        all.push({
            id: t.id,
            date: t.date,
            docNo: t.docNo,
            kind,
            palletId: t.palletId,
            palletName: palletName(t.palletId),
            qty: t.qty,
            effect,
            branchName: isAdjust ? 'ปรับยอดโดยระบบ' : branchName(ourSide),
        });
    }
    all.sort((a, b) => new Date(b.date).getTime() - new Date(a.date).getTime() || b.id - a.id);

    if (!showTotals) {
        // ยังไม่กระทบยอด: แสดงเฉพาะเอกสารรับ-คืนจริง
        // ตัดรายการปรับยอดภายใน และรายการคืนอัตโนมัติ (ไม่ใช่การคืนจริง) ออก
        const history = all.filter(h => h.kind === 'RECEIVE' || h.kind === 'RETURN');
        return { partner, showTotals, balances: [], history, aging: [], graceDays: partner.gracePeriod ?? 0 };
    }

    const balances: PartnerBalanceRow[] = pallets.map(palletId => {
        let received = 0, returned = 0, balance = 0;
        for (const h of all) {
            if (h.palletId !== palletId) continue;
            if (h.kind === 'RECEIVE') received += h.qty;
            if (h.kind === 'RETURN' || h.kind === 'AUTO') returned += h.qty;
            balance += h.effect;
        }
        return { palletId, palletName: palletName(palletId), received, returned, balance };
    });

    // อายุค้าง ใช้ผลจากรายงาน Aging เดิมของระบบ (ตัดช่องเงินออก)
    // ส่งเฉพาะแถวของคู่ค้ารายนี้ ไม่ต้องคำนวณคู่ค้าทุกรายทุกครั้งที่ข้อมูลเปลี่ยน
    const partnerRows = transactions.filter(t => t && (t.source === partnerId || t.dest === partnerId));
    const aging: PartnerAgingRow[] = getAgingRentalAnalysis(partnerRows, today).loans
        .filter(l => l.partnerId === partnerId)
        .map(l => ({
            docNo: l.docNo,
            palletId: l.palletId,
            palletName: palletName(l.palletId),
            borrowDate: l.borrowDate,
            ageDays: l.ageDays,
            qty: l.qty,
            overdueDays: l.overdueDays,
        }));

    return {
        partner,
        showTotals,
        balances,
        history: all,
        aging,
        graceDays: partner.gracePeriod ?? 0,
    };
};
